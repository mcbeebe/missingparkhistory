/* Shared photo viewer for the map (index.html) and the park pages (parks/*.html).
   One file: markup and styles are created here on first use.

   Script API (used by the map):
     PhotoViewer.open([{src, caption}, ...], startIndex)   -> true if it opened
     PhotoViewer.close()
     PhotoViewer.isOpen()

   Markup API (used by park pages, generated by scripts/build_park_pages.py):
     links with data-gallery="<name>" form one gallery; a link with
     data-gallery-open="<name>" and data-index="<n>" (a "+N more" tile) opens it at n.
     Those opens send GA4 park_photo_open. Without JS every link still opens the file.

   Zoom 100-500%: +/- buttons or keys, wheel (toward the cursor), double-click, pinch;
   drag to pan. At 100% a horizontal swipe changes photo. Esc, x or the backdrop closes.

   GA4 (all with viewer: map|park_page, gallery, photo_index, photos):
     photo_zoom  first zoom past 100% on a photo (method: button|key|wheel|double_click|pinch)
     photo_nav   moving to another photo (direction: next|prev, method: button|key|swipe) */
(function () {
  if (window.PhotoViewer) return;

  var MIN = 1, MAX = 5, STEP = 1.25;
  var CSS =
    '.pv{position:fixed;inset:0;z-index:20000;overflow:hidden;background:rgba(5,5,10,0.97);-webkit-backdrop-filter:blur(6px);backdrop-filter:blur(6px);display:flex;align-items:center;justify-content:center;font-family:-apple-system,BlinkMacSystemFont,"Segoe UI",sans-serif;outline:none}' +
    '.pv[hidden]{display:none}' +
    '.pv figure{position:relative;z-index:0;margin:0;max-width:min(92vw,1400px);display:flex;flex-direction:column;align-items:center;gap:10px}' +
    '.pv img{max-width:100%;max-height:calc(100vh - 120px);object-fit:contain;border-radius:6px;background:#111;touch-action:none;cursor:zoom-in;user-select:none;-webkit-user-select:none;transform-origin:center center;will-change:transform}' +
    '.pv figcaption{position:relative;z-index:1;display:flex;gap:14px;align-items:baseline;justify-content:center;flex-wrap:wrap;color:#ccc;font-size:14px;line-height:1.4;text-align:center;background:rgba(5,5,10,0.75);border-radius:14px;padding:4px 14px}' +
    '.pv .pv-count{color:#888;font-size:12px;white-space:nowrap}' +
    '.pv .pv-orig{color:#6d9eeb;font-size:12px;text-decoration:none;white-space:nowrap}' +
    '.pv button{position:absolute;z-index:1;margin:0;padding:0;background:rgba(255,255,255,0.08);border:1px solid rgba(255,255,255,0.15);color:#fff;border-radius:50%;width:44px;height:44px;font-size:22px;line-height:1;font-family:inherit;cursor:pointer;display:flex;align-items:center;justify-content:center}' +
    '.pv button:hover{background:rgba(255,255,255,0.18)}' +
    '.pv button:focus-visible{outline:2px solid #6d9eeb;outline-offset:2px}' +
    '.pv button[hidden]{display:none}' +
    '.pv .pv-close{top:14px;right:14px}' +
    '.pv .pv-prev{left:14px;top:50%;transform:translateY(-50%)}' +
    '.pv .pv-next{right:14px;top:50%;transform:translateY(-50%)}' +
    '.pv .pv-zoom{position:absolute;top:14px;left:50%;transform:translateX(-50%);z-index:1;display:flex;align-items:center;gap:6px;padding:4px 6px;background:rgba(20,20,30,0.85);border:1px solid rgba(255,255,255,0.12);border-radius:22px}' +
    '.pv .pv-zoom button{position:static;width:34px;height:34px;font-size:18px}' +
    '.pv .pv-zoom-level{min-width:44px;text-align:center;color:#ccc;font-size:12px;font-variant-numeric:tabular-nums}' +
    '.pv .pv-hint{position:absolute;top:66px;left:50%;transform:translateX(-50%);z-index:1;padding:6px 14px;border-radius:14px;background:rgba(20,20,30,0.85);color:#aaa;font-size:12px;white-space:nowrap;pointer-events:none;opacity:0;transition:opacity .4s}' +
    '.pv .pv-hint.show{opacity:1}' +
    '@media(max-width:600px){.pv .pv-prev,.pv .pv-next{top:auto;bottom:14px;transform:none}.pv img{max-height:calc(100vh - 150px)}.pv figcaption{padding:4px 12px}}';

  var box, img, cap, count, orig, prevBtn, nextBtn, closeBtn, zoomBar, zoomLabel, hint;
  var photos = [], idx = 0, opener = null, hintShown = false, gallery = '', zoomedThisPhoto = false;
  var scale = 1, panX = 0, panY = 0;
  var pointers = {}, gesture = null, moved = false;

  function build() {
    var style = document.createElement('style');
    style.id = 'pv-style';
    style.textContent = CSS;
    document.head.appendChild(style);

    box = document.createElement('div');
    box.className = 'pv';
    box.hidden = true;
    box.tabIndex = -1;   // clicks on the photo keep focus (and keys) in the viewer
    box.setAttribute('role', 'dialog');
    box.setAttribute('aria-modal', 'true');
    box.setAttribute('aria-label', 'Photo viewer');
    box.innerHTML =
      '<button type="button" class="pv-close" aria-label="Close photo viewer">&times;</button>' +
      '<div class="pv-zoom" role="group" aria-label="Zoom">' +
        '<button type="button" data-zoom="out" aria-label="Zoom out">&minus;</button>' +
        '<span class="pv-zoom-level" aria-live="polite">100%</span>' +
        '<button type="button" data-zoom="in" aria-label="Zoom in">+</button>' +
        '<button type="button" data-zoom="reset" aria-label="Reset zoom">&#8634;</button>' +
      '</div>' +
      '<div class="pv-hint" aria-hidden="true">Scroll or pinch to zoom &middot; double-click to magnify &middot; drag to pan</div>' +
      '<button type="button" class="pv-prev" aria-label="Previous photo">&#8249;</button>' +
      '<figure><img alt="" draggable="false"><figcaption><span class="pv-cap"></span>' +
      '<span class="pv-count" aria-live="polite"></span>' +
      '<a class="pv-orig" target="_blank" rel="noopener">Open original &#8599;</a></figcaption></figure>' +
      '<button type="button" class="pv-next" aria-label="Next photo">&#8250;</button>';
    document.body.appendChild(box);
    img = box.querySelector('img');
    cap = box.querySelector('.pv-cap');
    count = box.querySelector('.pv-count');
    orig = box.querySelector('.pv-orig');
    prevBtn = box.querySelector('.pv-prev');
    nextBtn = box.querySelector('.pv-next');
    closeBtn = box.querySelector('.pv-close');
    zoomBar = box.querySelector('.pv-zoom');
    zoomLabel = box.querySelector('.pv-zoom-level');
    hint = box.querySelector('.pv-hint');

    closeBtn.addEventListener('click', close);
    prevBtn.addEventListener('click', function () { go(-1, 'button'); });
    nextBtn.addEventListener('click', function () { go(1, 'button'); });
    zoomBar.addEventListener('click', function (e) {
      var b = e.target.closest('[data-zoom]');
      if (!b) return;
      var z = b.getAttribute('data-zoom');
      if (z === 'reset') resetZoom(); else zoomTo(z === 'in' ? scale * STEP : scale / STEP, undefined, undefined, 'button');
    });
    box.addEventListener('click', function (e) {
      if (moved) { moved = false; return; }   // the end of a drag is not a backdrop click
      if (e.target === box) close();
    });

    img.addEventListener('wheel', function (e) {
      e.preventDefault();
      zoomTo(e.deltaY < 0 ? scale * STEP : scale / STEP, e.clientX, e.clientY, 'wheel');
    }, { passive: false });
    img.addEventListener('dblclick', function (e) {
      if (scale > 1) resetZoom(); else zoomTo(2.5, e.clientX, e.clientY, 'double_click');
    });
    img.addEventListener('pointerdown', down);
    img.addEventListener('pointermove', move);
    img.addEventListener('pointerup', up);
    img.addEventListener('pointercancel', up);
  }

  // Keys work wherever focus is while the viewer is open, and never reach the page
  // underneath (so Esc closes the viewer, not the map's side panel too).
  window.addEventListener('keydown', function (e) {
    if (!isOpen()) return;
    var handled = true;
    if (e.key === 'Escape') close();
    else if (e.key === 'ArrowLeft') go(-1, 'key');
    else if (e.key === 'ArrowRight') go(1, 'key');
    else if (e.key === '+' || e.key === '=') zoomTo(scale * STEP, undefined, undefined, 'key');
    else if (e.key === '-' || e.key === '_') zoomTo(scale / STEP, undefined, undefined, 'key');
    else if (e.key === '0') resetZoom();
    else if (e.key === 'Tab') trapFocus(e);
    else handled = false;
    if (handled) {
      if (e.key !== 'Tab') e.preventDefault();
      e.stopPropagation();
    }
  }, true);

  /* ---- zoom & pan ---- */

  function apply() {
    img.style.transform = 'translate(' + panX + 'px,' + panY + 'px) scale(' + scale + ')';
    img.style.cursor = scale > 1 ? 'grab' : 'zoom-in';
    zoomLabel.textContent = Math.round(scale * 100) + '%';
  }

  // Keep the photo from being dragged off screen.
  function clampPan() {
    var w = img.offsetWidth, h = img.offsetHeight;
    var mx = Math.max(0, (w * scale - w) / 2), my = Math.max(0, (h * scale - h) / 2);
    panX = Math.max(-mx, Math.min(mx, panX));
    panY = Math.max(-my, Math.min(my, panY));
  }

  // Zoom to `next`, keeping the point under (cx, cy) still; default is the photo's centre.
  function zoomTo(next, cx, cy, method) {
    next = Math.max(MIN, Math.min(MAX, next));
    if (next === scale) return;
    if (next > 1 && !zoomedThisPhoto) {
      zoomedThisPhoto = true;
      track('photo_zoom', { method: method || 'other' });
    }
    var r = img.getBoundingClientRect();
    var baseX = r.left + r.width / 2 - panX, baseY = r.top + r.height / 2 - panY;
    var px = (cx === undefined ? baseX + panX : cx) - baseX;
    var py = (cy === undefined ? baseY + panY : cy) - baseY;
    panX = px - (px - panX) * next / scale;
    panY = py - (py - panY) * next / scale;
    scale = next;
    if (scale === 1) panX = panY = 0;
    clampPan();
    apply();
  }

  function resetZoom() {
    scale = 1; panX = panY = 0;
    apply();
  }

  function down(e) {
    pointers[e.pointerId] = { x: e.clientX, y: e.clientY };
    try { img.setPointerCapture(e.pointerId); } catch (err) {}
    var ids = Object.keys(pointers);
    if (ids.length === 2) {
      var a = pointers[ids[0]], b = pointers[ids[1]];
      gesture = { type: 'pinch', dist: Math.hypot(a.x - b.x, a.y - b.y), scale: scale };
    } else {
      gesture = { type: scale > 1 ? 'pan' : 'swipe', x: e.clientX, y: e.clientY, panX: panX, panY: panY };
      if (scale > 1) img.style.cursor = 'grabbing';
    }
    moved = false;
  }

  function move(e) {
    if (!pointers[e.pointerId] || !gesture) return;
    pointers[e.pointerId] = { x: e.clientX, y: e.clientY };
    if (gesture.type === 'pinch') {
      var ids = Object.keys(pointers);
      if (ids.length < 2) return;
      var a = pointers[ids[0]], b = pointers[ids[1]];
      zoomTo(gesture.scale * Math.hypot(a.x - b.x, a.y - b.y) / gesture.dist, (a.x + b.x) / 2, (a.y + b.y) / 2, 'pinch');
      moved = true;
    } else if (gesture.type === 'pan') {
      panX = gesture.panX + e.clientX - gesture.x;
      panY = gesture.panY + e.clientY - gesture.y;
      clampPan();
      apply();
      img.style.cursor = 'grabbing';
      if (Math.abs(e.clientX - gesture.x) + Math.abs(e.clientY - gesture.y) > 4) moved = true;
    }
  }

  function up(e) {
    if (!pointers[e.pointerId]) return;
    delete pointers[e.pointerId];
    if (gesture && gesture.type === 'swipe') {
      var dx = e.clientX - gesture.x, dy = e.clientY - gesture.y;
      if (Math.abs(dx) > 50 && Math.abs(dx) > Math.abs(dy)) { moved = true; go(dx < 0 ? 1 : -1, 'swipe'); }
    }
    if (Object.keys(pointers).length === 0) {
      gesture = null;
      if (scale > 1) img.style.cursor = 'grab';
    } else if (gesture && gesture.type === 'pinch') {
      var id = Object.keys(pointers)[0];   // one finger left: carry on panning from here
      gesture = { type: 'pan', x: pointers[id].x, y: pointers[id].y, panX: panX, panY: panY };
    }
  }

  /* ---- viewer ---- */

  function trapFocus(e) {
    var items = [].filter.call(box.querySelectorAll('button, a[href]'), function (el) { return !el.hidden; });
    var first = items[0], last = items[items.length - 1];
    if (!box.contains(document.activeElement) || document.activeElement === box) { e.preventDefault(); (e.shiftKey ? last : first).focus(); }
    else if (e.shiftKey && document.activeElement === first) { e.preventDefault(); last.focus(); }
    else if (!e.shiftKey && document.activeElement === last) { e.preventDefault(); first.focus(); }
  }

  function show() {
    var p = photos[idx];
    resetZoom();
    zoomedThisPhoto = false;
    img.src = p.src;
    img.alt = p.caption;
    cap.textContent = p.caption;
    count.textContent = photos.length > 1 ? (idx + 1) + ' / ' + photos.length : '';
    orig.href = p.src;
    prevBtn.hidden = nextBtn.hidden = photos.length < 2;
    [idx - 1, idx + 1].forEach(function (n) {   // warm the neighbours
      var q = photos[(n + photos.length) % photos.length];
      if (q) new Image().src = q.src;
    });
  }

  function go(step, method) {
    if (photos.length < 2) return;
    idx = (idx + step + photos.length) % photos.length;
    show();
    track('photo_nav', { direction: step > 0 ? 'next' : 'prev', method: method || 'other' });
  }

  function track(name, params) {
    if (typeof window.gtag !== 'function') return;
    params.viewer = /\/parks\//.test(location.pathname) ? 'park_page' : 'map';
    params.gallery = gallery;
    params.photo_index = idx;
    params.photos = photos.length;
    params.page_path = location.pathname;
    window.gtag('event', name, params);
  }

  function isOpen() {
    return !!box && !box.hidden;
  }

  // list: [{src, caption}] (name is accepted for caption too)
  // opts: {gallery, from} -- gallery names the set in GA4; from gets focus back on close.
  //       An element may be passed instead, as `from`.
  function open(list, start, opts) {
    opts = opts && opts.nodeType ? { from: opts } : (opts || {});
    var from = opts.from;
    photos = [].filter.call(list || [], function (p) { return p && p.src; }).map(function (p) {
      return { src: p.src, caption: p.caption != null ? String(p.caption) : String(p.name || '') };
    });
    if (!photos.length) return false;
    if (!box) build();
    gallery = String(opts.gallery || '');
    idx = Math.min(Math.max(start || 0, 0), photos.length - 1);
    opener = from || document.activeElement;
    show();
    box.hidden = false;
    document.body.style.overflow = 'hidden';
    closeBtn.focus();
    if (!hintShown) {
      hintShown = true;
      hint.classList.add('show');
      setTimeout(function () { hint.classList.remove('show'); }, 3000);
    }
    return true;
  }

  function close() {
    if (!isOpen()) return;
    box.hidden = true;
    resetZoom();
    pointers = {};
    gesture = null;
    img.removeAttribute('src');
    document.body.style.overflow = '';
    if (opener && opener.focus && document.contains(opener)) opener.focus();
  }

  window.PhotoViewer = { open: open, close: close, isOpen: isOpen };

  /* ---- park pages: data-gallery links ---- */

  function galleryLinks(name) {
    return document.querySelectorAll('a[data-gallery="' + String(name).replace(/["\\]/g, '') + '"]');
  }

  document.addEventListener('click', function (e) {
    if (e.defaultPrevented || e.button !== 0 || e.metaKey || e.ctrlKey || e.shiftKey || e.altKey) return;
    var more = e.target.closest && e.target.closest('a[data-gallery-open]');
    var link = !more && e.target.closest && e.target.closest('a[data-gallery]');
    var name, start, links;
    if (more) {
      name = more.getAttribute('data-gallery-open');
      start = parseInt(more.getAttribute('data-index'), 10) || 0;
      links = galleryLinks(name);
    } else if (link) {
      name = link.getAttribute('data-gallery');
      links = galleryLinks(name);
      start = [].indexOf.call(links, link);
    } else {
      return;
    }
    var list = [].map.call(links, function (a) {
      return { src: a.getAttribute('href'), caption: a.getAttribute('data-caption') || '' };
    });
    if (!open(list, start, { from: more || link, gallery: name })) return;
    e.preventDefault();
    if (typeof window.gtag === 'function') {
      var m = location.pathname.match(/\/parks\/([^\/]+?)(\.html)?$/);
      window.gtag('event', 'park_photo_open', {
        park: m ? m[1] : '', gallery: name, photo_index: idx, photos: photos.length, page_path: location.pathname
      });
    }
  });
})();
